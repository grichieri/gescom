-- ---------------------------------------------------------------------
-- verification_tokens  (enlaces de un solo uso que se mandan por correo)
-- type 1: verificar el correo tras registrarse
-- type 2: definir o restablecer la contraseña
-- Solo se usa cuando app.mail.enabled=true, pero la tabla existe siempre.
-- ---------------------------------------------------------------------
CREATE TABLE verification_tokens (
    token_id     bigint       GENERATED BY DEFAULT AS IDENTITY,
    user_id      integer      NOT NULL,
    token        varchar(64)  NOT NULL,
    type         smallint     NOT NULL,
    expires_at   timestamp    NOT NULL,
    used_at      timestamp,
    created_date timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_verification_tokens PRIMARY KEY (token_id),
    CONSTRAINT uq_verification_tokens_token UNIQUE (token),
    CONSTRAINT ck_verification_tokens_type CHECK (type IN (1, 2)),
    CONSTRAINT fk_verification_tokens_user FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE CASCADE
);
CREATE INDEX idx_verification_tokens_user_id ON verification_tokens (user_id);
